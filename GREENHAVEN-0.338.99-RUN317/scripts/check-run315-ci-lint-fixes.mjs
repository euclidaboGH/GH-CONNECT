import fs from "node:fs"
const read = (p) => fs.readFileSync(p, "utf8")
const checks = []
const add = (name, pass) => checks.push([name, Boolean(pass)])
const research = read("components/field/public-research-form.tsx")
const secureId = read("lib/secure-id.ts")
const context = read("contexts/ghc-context.tsx")
const heading = read("components/ghc/section-heading.tsx")
const designGate = read("scripts/check-pass14-product-design.mjs")
const workflow = read(".github/workflows/ci.yml")
add("public research home navigation uses Next Link", /import Link from "next\/link"/.test(research) && /<Link href="\/"/.test(research))
add("public research privacy navigation uses Next Link", /<Link href="\/privacy"/.test(research) && !/<a href="\/privacy"/.test(research))
add("secure ID source has no unknown TypeScript ESLint rule directives", !/@typescript-eslint\/no-require-imports/.test(secureId))
add("secure ID helpers retain cryptographic UUID and byte generation", /globalThis\.crypto/.test(secureId) && /randomUUID/.test(secureId) && /getRandomValues/.test(secureId))
const deleteComment = context.slice(context.indexOf("const deleteComment = useCallback"), context.indexOf("const addCommentReaction = useCallback"))
add("delete-comment callback declares state.posts dependency", /\}, \[addToast, state\.posts\]\)/.test(deleteComment))
add("shared section heading emits its design-system title class", /<h2 className="gh-section-title/.test(heading))
add("product-design gate validates dynamic package/release synchronization", /package and app release versions are synchronized/.test(designGate) && !/release 0\.236\.0/.test(designGate))
add("CI creates a diagnostic artifact when build fails before Next output exists", /Prepare Next\.js diagnostics artifact on failure/.test(workflow) && /ci-failure-context\.txt/.test(workflow))
add("CI artifact upload now requires the prepared diagnostics file", /if-no-files-found: error/.test(workflow))
for (const [name, pass] of checks) console.log(`${pass ? "PASS" : "FAIL"} ${name}`)
const failed = checks.filter(([, pass]) => !pass)
console.log(`\nRun 315 CI lint/build remediation: ${checks.length - failed.length}/${checks.length} passed`)
if (failed.length) process.exit(1)
