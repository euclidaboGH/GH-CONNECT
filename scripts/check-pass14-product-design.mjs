import fs from "node:fs"
const checks = []
const read = p => fs.readFileSync(p,"utf8")
const add = (name, ok) => checks.push([name, Boolean(ok)])
const pkg = JSON.parse(read("package.json"))
const release = read("lib/app-release.ts")
const css = read("app/globals.css")
const heading = read("components/ghc/section-heading.tsx")
const results = read("components/ghc/home-results-strip.tsx")
const chrome = read("components/ghc/page-chrome.tsx")
add("release 0.236.0", release.includes(`APP_RELEASE_VERSION = "${pkg.version}"`))
add("shared section hierarchy", heading.includes("SectionHeading") && heading.includes("gh-section-title"))
add("result surface uses shared hierarchy", results.includes("SectionHeading") && results.includes("gh-result-card"))
add("premium page chrome", chrome.includes("gh-page-chrome") && chrome.includes("gh-secondary-control"))
add("shared product tokens", css.includes("--gh-product-radius") && css.includes("--gh-product-raised"))
add("pointer-aware hover", css.includes("@media (hover:hover) and (pointer:fine)"))
add("reduced-motion protection", css.includes("@media (prefers-reduced-motion: reduce)") && css.includes(".gh-result-card"))
add("canonical navigation untouched", !results.includes('Wallet') && !heading.includes('Wallet'))
for (const [n,ok] of checks) console.log(`${ok ? "PASS" : "FAIL"} — ${n}`)
const failed=checks.filter(([,ok])=>!ok)
console.log(`\nPass 14 product-design gate: ${checks.length-failed.length}/${checks.length}`)
if(failed.length) process.exit(1)
