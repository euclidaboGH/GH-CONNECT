import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const auth = readFileSync('lib/server/economy/auth.ts', 'utf8')
const profileStore = readFileSync('lib/server/identity/profile-store.ts', 'utf8')
const profileRoute = readFileSync('app/api/profile/me/route.ts', 'utf8')
const onboardingRoute = readFileSync('app/api/auth/onboarding-complete/route.ts', 'utf8')
const middleware = readFileSync('middleware.ts', 'utf8')
const piAuth = readFileSync('app/api/auth/pi/route.ts', 'utf8')
const messaging = readFileSync('app/api/messaging/conversations/[conversationId]/messages/route.ts', 'utf8')
const rewardClaim = readFileSync('app/api/economy/rewards/claim/route.ts', 'utf8')

assert.match(auth, /typeof payload\.exp !== "number"/)
assert.match(auth, /payload\.exp <= nowSeconds/)
assert.match(auth, /payload\.nbf/)
assert.match(auth, /payload\.iat/)
assert.match(auth, /GHC_AUTH_JWT_ISSUER/)
assert.match(auth, /GHC_AUTH_JWT_AUDIENCE/)
assert.match(profileStore, /options: \{ allowOnboardedChange\?: boolean \}/)
assert.match(profileStore, /options\.allowOnboardedChange && typeof input\.onboarded === "boolean"/)
assert.match(profileRoute, /delete input\.onboarded/)
assert.match(profileRoute, /profile-write:\$\{auth\.userId\}/)
assert.match(profileRoute, /REQUEST_TOO_LARGE/)
assert.match(onboardingRoute, /allowOnboardedChange: true/)
assert.match(middleware, /CROSS_ORIGIN_MUTATION_BLOCKED/)
assert.match(middleware, /sec-fetch-site/)
assert.match(middleware, /matcher: \["\/api\/:path\*"\]/)
assert.match(piAuth, /checkRateLimit/)
assert.match(piAuth, /REQUEST_TOO_LARGE/)
assert.match(messaging, /appendMessage/)
assert.match(messaging, /checkRateLimit/)
assert.match(rewardClaim, /rpcClaimPending/)
assert.match(rewardClaim, /body\.amount/)
assert.match(rewardClaim, /body\.userId/)
console.log('Critical security hardening: 20 assertions passed')
