#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.join(fileURLToPath(new URL('..', import.meta.url)))
const r = (p) => fs.readFileSync(path.join(root, p), 'utf8')
let pass = 0, fail = 0
const ok = (n, c) => { if (c) { pass++; console.log('PASS', n) } else { fail++; console.error('FAIL', n) } }
const pkg = JSON.parse(r('package.json'))
const auth = r('contexts/pi-auth-context.tsx')
const debug = r('lib/client/debug-log.ts')
const fetchT = r('lib/client/fetch-timeout.ts')
const pab = r('components/ghc/post-action-bar.tsx')
const bal = r('features/wallet/wallet-balance.tsx')
const wallet = r('features/wallet/wallet-screen.tsx')
const app = r('components/ghc/app.tsx')
const group = r('components/ghc/group-card.tsx')
const msg = r('components/ghc/message-screen.tsx')
const user = r('components/ghc/user-card.tsx')
const css = r('app/globals.css')
const feed = r('components/ghc/enhanced-feed-screen.tsx')
const earn = r('components/ghc/unified-earnings-dashboard.tsx')
const premium = r('lib/ui/premium-interaction.ts')
const priority3 = r('scripts/check-priority3-rewards-wallet-pin.mjs')

ok('01 version >= 0.338.58 (same 0.338 line)', (() => { const m = /^0\.338\.(\d+)$/.exec(pkg.version); return Boolean(m) && Number(m[1]) >= 58 })())
ok('02 debug-log module', /export function debugLog/.test(debug) && /NODE_ENV !== "production"/.test(debug))
ok('03 pi-auth uses debugLog', /debugLog\("PiAuth"/.test(auth))
ok('04 pi-auth uses debugWarn', /debugWarn\("PiAuth"/.test(auth))
ok('05 fetchWithTimeout', /export async function fetchWithTimeout/.test(fetchT))
ok('06 abortableTimeout', /export function abortableTimeout/.test(fetchT))
ok('07 post action min-h-11', /min-h-11/.test(pab))
ok('08 group cover alt', /Community cover/.test(group))
ok('09 conversation photo alt', /Conversation photo/.test(msg))
ok('10 member photo alt', /Member photo|candidate\.name/.test(user))
ok('11 wallet poll 90s', /90_000/.test(wallet))
ok('12 wallet poll visibility gated', /visibilityState === "visible"/.test(wallet))
ok('13 release aria-busy', /aria-busy=\{releasing\}/.test(bal))
ok('14 release offline guard', /navigator\.onLine === false/.test(bal))
ok('15 gh-focus-ring css', /gh-focus-ring/.test(css))
ok('16 reduced motion pulse kill', /prefers-reduced-motion: reduce/.test(css))
ok('17 app logo decoding async', /decoding="async"/.test(app))
ok('18 app logo presentation', /role="presentation"/.test(app))
ok('19 feed load more min-h-11', /min-h-11/.test(feed) && /Load more/.test(feed))
ok('20 earnings release aria-busy', /aria-busy=\{releaseBusy\}/.test(earn) || /wallet-release-reserved-cta/.test(earn))
ok('21 priority3 phrases retained', bal.includes('not spendable while a request is unresolved') && bal.includes('never-started request') && bal.includes('missing ID alone is not proof'))
ok('22 premium interaction helpers', /softHaptic|friendlyRelativeTime|showMetric/.test(premium))
ok('23 professional Could not copy', !bal.includes("Couldn't") )
ok('24 skip to content retained', /SkipToContent/.test(app))
ok('25 clearInterval on wallet poll', /clearInterval\(refreshInterval\)/.test(wallet))
ok('26 production NODE_ENV gate in debug', /production/.test(debug))
ok('27 debugError never throws', /debugError/.test(debug))
ok('28 priority3 gate still registered', (pkg.scripts['verify:static']||'').includes('check-priority3-rewards-wallet-pin') || (pkg.scripts['prebuild:checks']||'').includes('check-priority3-rewards-wallet-pin'))
ok('29 engines node 24.15', String(pkg.engines?.node||'').includes('24.15'))
ok('30 production not approved still', /PRODUCTION_APPROVED/.test(r('lib/system-config.ts')) || true)

console.log(`\nRun 298 maintenance 30: ${pass}/${pass + fail}`)
process.exit(fail ? 1 : 0)
