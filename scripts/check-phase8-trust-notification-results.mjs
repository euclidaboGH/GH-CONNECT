import fs from 'node:fs'
const checks = []
const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')
const notif = read('components/ghc/notification-bell.tsx')
const sessions = read('components/ghc/active-sessions-panel.tsx')
const pkg = JSON.parse(read('package.json'))
const test = (name, ok) => checks.push([name, Boolean(ok)])
test('release version synchronized', read('lib/app-release.ts').includes(`APP_RELEASE_VERSION = "${pkg.version}"`))
test('notification center has priority mode', notif.includes('"priority"') && notif.includes('Priority'))
test('priority notifications are unread-only', notif.includes('!n.read && priorityTypes.has(n.type)'))
test('priority covers messages', notif.includes('"message"'))
test('priority covers marketplace orders', notif.includes('"marketplace_order"'))
test('priority covers financial notices', notif.includes('"payment"') && notif.includes('"ghc_received"'))
test('session security summary exists', sessions.includes('Session security summary'))
test('other-device count exists', sessions.includes('Other devices'))
test('unrecognized-device guidance exists', sessions.includes('If you do not recognize a device'))
for (const [name, ok] of checks) console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`)
const failed = checks.filter(([,ok]) => !ok)
console.log(`\n${checks.length-failed.length}/${checks.length} PASS`)
if (failed.length) process.exit(1)
