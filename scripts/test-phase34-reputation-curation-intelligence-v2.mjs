import fs from 'node:fs'
import path from 'node:path'

const root=process.cwd()
const fail=[]
const pass=[]
const check=(name,ok,detail='')=>(ok?pass:fail).push(`${ok?'PASS':'FAIL'} ${name}${detail?` — ${detail}`:''}`)
const read=(f)=>fs.readFileSync(path.join(root,f),'utf8')
const migration=read('supabase/migrations/20261023030002_gh_reputation_curation_intelligence_v2.sql')
const route=read('app/api/social/posts/[id]/curation/route.ts')
const weight=read('lib/server/ghpv/vote-weight.ts')
const intel=read('lib/server/reputation/intelligence.ts')
const api=read('app/api/social/reputation/intelligence/route.ts')
check('Phase 34 migration exists',migration.includes('gh_reputation_intelligence'))
check('Multi-dimensional reputation state',/creator_quality.*judgment_calibration.*community_integrity.*economic_value.*growth_xp/s.test(migration))
check('Curator activity audit exists',migration.includes('gh_curator_activity_events'))
check('Risk score is server-derived',migration.includes('v_author_concentration') && migration.includes('v_rapid_ratio'))
check('Daily curation cap enforced',migration.includes('v_votes>=120') && migration.includes("'DAILY_CURATION_LIMIT'"))
check('Curation preflight enforces self-curation',migration.includes("'SELF_CURATION_FORBIDDEN'"))
check('Curation preflight enforces blocks',migration.includes('ghc_user_blocks'))
check('Atomic pipeline calls preflight',migration.includes('v_guard := public.gh_curation_preflight'))
check('Atomic pipeline records activity',migration.includes('PERFORM public.gh_curation_activity_record'))
check('No GHC minting in V2 migration',!migration.includes('ghc_execute_earn'))
check('No client authority in curation route',route.includes('stripClientAuthority(body)'))
check('Daily cap mapped to 429',route.includes('err === "DAILY_CURATION_LIMIT" ? 429 : 403'))
check('Stored intelligence can become curation authority',weight.includes('loadStoredIntelligence') && weight.includes('intelligence.curationPower'))
check('Formula fallback preserved',weight.includes('const computedPower = computeCurationPower'))
check('Public intelligence projection omits risk',migration.includes('gh_reputation_intelligence_get') && !/riskScore.*gh_reputation_intelligence_get/.test(migration.split('CREATE OR REPLACE FUNCTION public.gh_reputation_intelligence_get')[1]||''))
check('Server intelligence module exists',intel.includes('refreshReputationIntelligence') && intel.includes('getPublicReputationIntelligence'))
check('Authenticated intelligence API exists',api.includes('resolveAuthenticatedUser') && api.includes('refreshReputationIntelligence'))
const migrations=fs.readdirSync(path.join(root,'supabase/migrations')).filter(n=>/^\d{14}_.+\.sql$/.test(n))
check('Migration inventory is 131',migrations.length===131,`count=${migrations.length}`)
console.log([...pass,...fail].join('\n'))
console.log(`\nPhase 34 checks: ${pass.length}/${pass.length+fail.length}`)
if(fail.length) process.exit(1)
