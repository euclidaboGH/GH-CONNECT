import fs from "node:fs"
import assert from "node:assert/strict"
const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), "utf8")
const approve = read("app/api/payments/approve/route.ts")
const authPi = read("app/api/auth/pi/route.ts")
const missions = read("app/api/economy/missions/progress/route.ts")
const utility = read("app/api/economy/utility/route.ts")
const listingPayment = read("lib/server/marketplace/verify-listing-fee-payment.ts")
const utilityCatalog = read("app/api/economy/catalog/route.ts")
const utilityUi = read("components/ghc/ghc-utility-panel.tsx")
const rewardsUi = read("components/ghc/rewards-centre-screen.tsx")
const purchaseGhc = read("app/api/economy/purchase-ghc/route.ts")
const genericIntents = read("app/api/payments/intents/route.ts")

assert.match(approve, /if \(intent\?\.userId && !auth\)/, "bound Pi payment intents require authenticated owner in every environment")
assert.doesNotMatch(approve, /intent\.userId &&\s*!auth &&\s*\(process\.env\.VERCEL_ENV/, "ownership protection is not production-only")
assert.match(authPi, /const rawBody = await request\.text\(\)/, "Pi auth reads bounded raw body before JSON parse")
assert.match(authPi, /Buffer\.byteLength\(rawBody, "utf8"\) > 16_384/, "Pi auth enforces actual body byte cap")
assert.match(authPi, /accessToken\.length > 8_192/, "Pi auth caps token length")
assert.match(missions, /MISSION_VERIFICATION_UNAVAILABLE/, "mission reward issuance fails closed without authoritative proof")
assert.match(missions, /MISSION_PROGRESS_NOT_PERSISTED/, "mission endpoint does not claim an unpersisted completion")
assert.doesNotMatch(missions, /computeAndCommitActivityEmissionDurable/, "client mission code cannot directly consume emission budget")
assert.match(utility, /BOOST_EFFECT_NOT_CONFIGURED/, "boost purchases are blocked before debit until effect is durable")
assert.ok(utility.indexOf("BOOST_EFFECT_NOT_CONFIGURED") < utility.indexOf("const spend = await executeDurableGhcSpend"), "boost fail-closed gate runs before wallet debit")
assert.match(utility, /utility:\$\{purpose\}:\$\{scopedUser\}:\$\{createHash\("sha256"\)/, "utility idempotency keys are namespaced and hashed")
assert.match(listingPayment, /const referenceListing = ref\.startsWith\("marketplace_listing_fee_"\)/, "listing fee references are parsed into an explicit binding")
assert.match(listingPayment, /if \(metaListing && referenceListing && metaListing !== referenceListing\) return false/, "conflicting listing binding channels are rejected")
assert.doesNotMatch(listingPayment, /new Set\(\["marketplace", "sponsored_listing", "other"\]\)/, "generic 'other' payment intents cannot satisfy listing fee")
assert.match(listingPayment, /intent\.provider !== "pi"/, "listing fee verification requires Pi payment provider")
assert.match(utilityCatalog, /unavailableReason: "Temporarily unavailable: durable activation is not configured/, "catalog exposes unavailable utility state")
assert.match(utilityUi, /item\.available === false/, "UI disables unavailable purchases before request")
assert.match(rewardsUi, /Mission rewards (are paused|remain paused)/, "rewards UI explains mission reward pause")
assert.match(rewardsUi, /Daily Claim rewards mature after 48 hours/, "rewards UI states the authoritative 48-hour maturity rule")
assert.match(purchaseGhc, /intent\.metadata\?\.kind !== "ghc_pack"/, "GHC acquisition requires dedicated server-owned pack metadata")
assert.match(purchaseGhc, /intent\.provider !== "pi"/, "GHC acquisition requires Pi provider")
assert.match(purchaseGhc, /ghc_pack_\$\{pack\.productId\}:\$\{auth\.userId\}:/, "GHC acquisition requires a user-scoped pack reference")
assert.match(genericIntents, /USE_GHC_PACK_INTENT_ROUTE/, "generic payment intent route cannot forge reserved GHC pack metadata")
assert.match(genericIntents, /requestedCurrency !== "PI"/, "generic payment intent route rejects currency coercion")
assert.match(genericIntents, /requestedCurrency === "GHC"/, "GHC rejection is case-insensitive")
console.log("Payment/economy stabilization contracts: 24/24 passed")
