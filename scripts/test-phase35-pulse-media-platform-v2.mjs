import fs from 'node:fs'
import path from 'node:path'
const root=process.cwd(); const pass=[]; const fail=[]
const read=f=>fs.readFileSync(path.join(root,f),'utf8')
const check=(name,ok)=> (ok?pass:fail).push(`${ok?'PASS':'FAIL'} ${name}`)
const migration=read('supabase/migrations/20261023040001_gh_pulse_media_platform_v2.sql')
const intent=read('app/api/media/direct-upload-intent/route.ts')
const complete=read('app/api/media/direct-upload-complete/route.ts')
const upload=read('lib/media/upload-client.ts')
const pulse=read('app/api/social/short-video/route.ts')
const attention=read('app/api/social/posts/[id]/attention/route.ts')
const video=read('lib/media/video-inspection.ts')
check('durable upload session table',migration.includes('gh_media_upload_sessions'))
check('upload session owner/path protection',migration.includes('gh_media_upload_path_owned'))
check('upload session RLS deny-all',migration.includes('gh_media_upload_sessions_no_client') && migration.includes('USING (false) WITH CHECK (false)'))
check('upload session create/get/finalize RPCs',migration.includes('gh_media_upload_session_create') && migration.includes('gh_media_upload_session_get') && migration.includes('gh_media_upload_session_finalize'))
check('direct intent issues uploadId',intent.includes('uploadId') && intent.includes('gh_media_upload_session_create'))
check('completion requires uploadId',complete.includes('INVALID_UPLOAD_ID') && complete.includes('gh_media_upload_session_get'))
check('completion is idempotent',complete.includes('idempotent: true') && migration.includes("status='finalized'"))
check('stable media id derives from upload session',complete.includes('id: `media_${uploadId.slice(7)}`'))
check('client sends uploadId during completion',upload.includes('uploadId: intent.uploadId'))
check('short-video feed uses dedicated server RPC',migration.includes('gh_short_video_list') && pulse.includes('socialRpc("gh_short_video_list"'))
check('short-video modes',migration.includes("('latest','following','trending')") && pulse.includes('trending'))
check('short-video stable cursor',migration.includes('p_before_ms') && migration.includes('p_before_id') && pulse.includes('stableCursor'))
check('canonical visibility is reused',migration.includes('gh_post_viewer_can_read'))
check('attention milestones server allowlist',migration.includes("'progress_25','progress_50','progress_75'"))
check('video inspection blocks oversized/long Pulse videos',video.includes('MAX_PULSE_DURATION_MS') && video.includes('PULSE_VIDEO_TOO_LONG') && video.includes('PULSE_FILE_TOO_LARGE'))
check('attention API accepts progress events',attention.includes('isAttentionEventType'))
const migrations=fs.readdirSync(path.join(root,'supabase/migrations')).filter(n=>/^\d{14}_.+\.sql$/.test(n))
check('migration inventory is 131',migrations.length===131)
console.log([...pass,...fail].join('\n'))
console.log(`\nPhase 35 checks: ${pass.length}/${pass.length+fail.length}`)
if(fail.length) process.exit(1)
