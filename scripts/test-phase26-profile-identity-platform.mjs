import fs from 'node:fs'
const read = (p) => fs.readFileSync(p, 'utf8')
const checks = []
const check = (name, ok) => { checks.push([name, Boolean(ok)]); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`) }
const api = read('app/api/social/profile/[userId]/route.ts')
const app = read('components/ghc/app.tsx')
const client = read('lib/social/client.ts')
const owner = read('components/ghc/profile-screen.tsx')
const identity = read('components/ghc/profile-identity-overview.tsx')
const timeline = read('app/api/social/profile/[userId]/posts/route.ts')
check('public profile requires authenticated viewer', api.includes('AUTH_REQUIRED') && api.includes('resolveAuthenticatedUser'))
check('public profile rejects blocked relationship', api.includes('relationship.blocked') && api.includes('PROFILE_UNAVAILABLE'))
check('private profile fails closed', api.includes('profileVisibility === "hidden"') && api.includes('PROFILE_PRIVATE'))
check('matches-only profile fails closed without canonical match proof', api.includes('profileVisibility === "matches-only"') && api.includes('fail-closed'))
check('public projection strips private economy fields', api.includes('projectPublicProfile') && api.includes('.wallet') && api.includes('.membership'))
check('public identity includes server reputation', api.includes('getReputationState(targetUserId)'))
check('public identity includes authoritative follow counts', api.includes('gh_follow_status') && api.includes('followersCount'))
check('social client exposes canonical profile read', client.includes('export async function socialGetProfile'))
check('cross-surface profile open hydrates outside discovery results', app.includes('socialGetProfile(userId)') && app.includes('isSample: false'))
check('owner identity overview reads follow reputation achievements together', identity.includes('/api/social/follows') && identity.includes('/api/social/reputation') && identity.includes('/api/profile/achievements'))
check('owner profile stats prefer authoritative follow counts', owner.includes('authoritativeFollowCounts?.following') && owner.includes('authoritativeFollowCounts?.followers'))
check('identity overview refreshes on social and reputation events', identity.includes('ghc:social-mutation') && identity.includes('ghc:reputation-updated'))
check('profile timeline remains viewer-authorized server path', timeline.includes('p_viewer_id: auth.userId') && timeline.includes('filterVisibleSocialPosts'))
check('profile timeline retains stable composite cursor', timeline.includes('beforeId') && timeline.includes('nextBeforeId'))
const failed = checks.filter(([,ok]) => !ok)
console.log(`\nPhase 26 profile/identity contract: ${checks.length-failed.length}/${checks.length} PASS`)
if (failed.length) process.exit(1)
