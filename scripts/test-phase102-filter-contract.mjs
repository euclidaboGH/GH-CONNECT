import assert from "node:assert/strict"
import { parseIsoDate, parseFiniteRange, parseLocationRange, parseFilterQuery, matchesFilterDateRange, matchesFilterNumberRange, matchesFilterCategory, matchesFilterCurrencyRange, haversineDistanceKm, serializeFilterQuery } from "../lib/filtering/filter-contract.ts"
assert.equal(parseIsoDate("2026-11-08"), "2026-11-08")
assert.equal(parseIsoDate("2026-02-30"), null)
assert.deepEqual(parseFiniteRange("10", "25"), { min: 10, max: 25 })
assert.equal(parseFiniteRange("30", "20"), null)
assert.equal(parseFiniteRange("NaN", "20"), null)
assert.deepEqual(parseLocationRange("51.5072", "-0.1276", "25"), { latitude: 51.5072, longitude: -0.1276, radiusKm: 25 })
assert.equal(parseLocationRange("91", "0", "5"), null)
assert.equal(parseLocationRange("51", "0", null), null)
const parsed = parseFilterQuery(new URLSearchParams("q=green%20haven&category=books&from=2026-01-01&to=2026-01-31&min=5&max=100&sort=price&direction=asc&limit=20"), { sorts: ["price"] })
assert.equal(parsed.q, "green haven")
assert.equal(parsed.category, "books")
assert.equal(parsed.min, 5)
assert.equal(parsed.max, 100)
assert.equal(parseFilterQuery(new URLSearchParams("from=2026-02-01&to=2026-01-01")), null)
assert.equal(parseFilterQuery(new URLSearchParams("sort=unsupported"), { sorts: ["price"] }), null)
assert.equal(matchesFilterDateRange(Date.parse("2026-01-31T23:59:59.999Z"), { from: "2026-01-01", to: "2026-01-31" }), true)
assert.equal(matchesFilterDateRange(Date.parse("2026-02-01T00:00:00.000Z"), { from: "2026-01-01", to: "2026-01-31" }), false)
assert.equal(matchesFilterNumberRange(undefined, { min: null, max: null }), true)
assert.equal(matchesFilterDateRange(null, { from: null, to: null }), true)
assert.equal(matchesFilterNumberRange(10, { min: 10, max: 20 }), true)
assert.equal(matchesFilterNumberRange(21, { min: 10, max: 20 }), false)
assert.equal(matchesFilterCategory("Books", "books"), true)
assert.equal(matchesFilterCurrencyRange(20, "GHC", { min: 10, max: 30 }, "GHC"), true)
assert.equal(matchesFilterCurrencyRange(20, "PI", { min: 10, max: 30 }, "GHC"), false)
assert.equal(matchesFilterCurrencyRange(20, "GHC", { min: 10, max: 30 }, "all"), false)
assert.equal(matchesFilterCurrencyRange(20, "PI", { min: null, max: null }, "all"), true)
assert.equal(haversineDistanceKm({ latitude: 51.5072, longitude: -0.1276 }, { latitude: 51.5072, longitude: -0.1276 }), 0)
const roundTrip = serializeFilterQuery({ q: "test", min: 3, max: 8, from: "2026-01-01", direction: "asc" })
assert.equal(roundTrip.get("q"), "test")
assert.equal(roundTrip.get("min"), "3")
assert.equal(roundTrip.get("from"), "2026-01-01")
console.log("Phase 10.2 filter contract tests: 28/28 passed")
