import fs from "node:fs"
const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), "utf8")
const checks = []
const check = (name, ok) => { checks.push([name, Boolean(ok)]); console.log(`${ok ? "PASS" : "FAIL"} — ${name}`) }
const pkg = JSON.parse(read("package.json"))
const release = read("lib/app-release.ts")
const model = read("lib/domains/adapters/community-outcome.ts")
const card = read("components/ghc/community-outcome-card.tsx")
const hub = read("components/ghc/premium-community-hub.tsx")
check("release metadata is 0.244.0", release.includes(`APP_RELEASE_VERSION = "${pkg.version}"`))
check("community outcome model exists", model.includes("buildCommunityOutcome") && model.includes("CommunityOutcome"))
check("outcome prioritizes real attention", model.includes("boardUnread") && model.includes("activePolls") && model.includes("upcomingEvents"))
check("polls and challenges remain participation surfaces", model.includes('kind: "poll"') && model.includes('kind: "challenge"'))
check("no fake financial outcomes", !model.includes("income") && !model.includes("guaranteed") && !model.includes("roi"))
check("outcome card is accessible", card.includes("aria-labelledby") && card.includes("focus-visible:ring"))
check("hub integrates outcome card", hub.includes("CommunityOutcomeCard") && hub.includes("buildCommunityOutcome"))
check("actions route to existing community spaces", hub.includes('setTab("events")') && hub.includes('setTab("board")') && hub.includes('onOpenChat?.()'))
check("community chat remains distinct", hub.includes('Board</span> = posts & events') && hub.includes('Chat</span> = live member talk'))
check("canonical bottom navigation is not changed", !hub.includes("bottom navigation") && !hub.includes('setTab("wallet")'))
const failed = checks.filter(([, ok]) => !ok)
console.log(`\nPass 22 Community Outcomes: ${checks.length - failed.length}/${checks.length} passed`)
if (failed.length) process.exit(1)
