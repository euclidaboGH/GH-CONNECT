#!/usr/bin/env node
/** Independent marketplace/community safety and feature-wiring regression gate. */
import { readFileSync } from 'node:fs'
const read = (p) => readFileSync(p, 'utf8')
const checks = []
const test = (name, ok) => { checks.push(Boolean(ok)); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`) }

const listing = read('app/api/marketplace/listings/route.ts')
const orders = read('app/api/marketplace/orders/route.ts')
const pay = read('app/api/marketplace/orders/[orderId]/pay/route.ts')
const transition = read('app/api/marketplace/orders/[orderId]/transition/route.ts')
const commerce = read('app/api/marketplace/orders/[orderId]/commerce/route.ts')
const timeline = read('app/api/marketplace/orders/[orderId]/timeline/route.ts')
const saves = read('app/api/marketplace/saves/route.ts')
const mapper = read('lib/marketplace/record-mappers.ts')
const variant = read('lib/marketplace/product-variants.ts')
const fulfilment = read('lib/marketplace/fulfilment.ts')
const rev = read('lib/server/marketplace/commission.ts')
const reconcile = read('app/api/marketplace/payouts/[requestId]/reconcile/route.ts')
const marketplaceMigration = read('supabase/migrations/20261107190001_marketplace_fulfilment_tracking_timeline.sql')
const marketStore = read('lib/server/marketplace/order-store.ts')

// Marketplace: 20 independent source-level safety and wiring controls.
test('M01 listing writes require authenticated session', /resolveAuthenticatedUser/.test(listing))
test('M02 client seller identity is ignored', /void body\.sellerId/.test(listing))
test('M03 listing writes use durable fail-closed throttling', /failClosed:\s*true/.test(listing))
test('M04 listing currency is restricted to supported rails', /\["GHC",\s*"PI"\]/.test(listing))
test('M05 price range filters require explicit currency', /PRICE_CURRENCY_REQUIRED/.test(listing))
test('M06 unsupported geo-radius filters fail honestly', /LOCATION_FILTER_UNSUPPORTED/.test(listing))
test('M07 variant SKU inventory is bounded', /INVALID_PRODUCT_VARIANTS/.test(listing) && /100/.test(variant))
test('M08 orders are created through server API', /export async function POST/.test(orders))
test('M09 order creation has durable fail-closed throttling', /failClosed:\s*true/.test(orders))
test('M10 payment mutations have durable fail-closed throttling', /failClosed:\s*true/.test(pay))
test('M11 payment is bound to authenticated buyer', /order\.buyerId !== auth\.userId/.test(pay))
test('M12 Pi payment recovery is idempotent', /idempotent:\s*true/.test(pay) && /priorIntent/.test(pay))
test('M13 GHC spending is routed through server spend authority', /ghcSpendRef|spend/.test(pay))
test('M14 order transitions are participant-scoped', /order\.buyerId !== auth\.userId && order\.sellerId !== auth\.userId/.test(transition))
test('M15 buyer confirmation is gated by delivery state in database', /delivery_status NOT IN \('delivered','service_active'\)/.test(marketplaceMigration) && /DELIVERY_NOT_CONFIRMED/.test(marketplaceMigration))
test('M16 fulfilment actions are participant-scoped', /order\.buyerId !== auth\.userId && order\.sellerId !== auth\.userId/.test(commerce))
test('M17 fulfilment parser is centralized', /parseMarketplaceFulfilmentInput/.test(commerce) && /parseMarketplaceFulfilmentInput/.test(fulfilment))
test('M18 timeline is participant-private and uncached', /auth\.userId/.test(timeline) && /no-store/.test(timeline))
test('M19 durable order store refuses production memory fallback', /isProd\(\)/.test(marketStore) && /return false|return null/.test(marketStore))
test('M20 seller commission is server-calculated', /commission/i.test(rev) && !/body\.commission/.test(rev))
test('M21 saved listing reads and writes use durable fail-closed throttling', (saves.match(/failClosed:\s*true/g) || []).length >= 2)
test('M22 saved-listing RPC transport has a bounded timeout', /AbortSignal\.timeout\(8_000\)/.test(saves))

const community = read('app/api/communities/route.ts')
const join = read('app/api/communities/[id]/join/route.ts')
const roles = read('app/api/communities/[id]/roles/route.ts')
const requests = read('app/api/communities/[id]/requests/route.ts')
const platform = read('app/api/communities/[id]/platform/route.ts')
const chat = read('app/api/communities/[id]/chat/route.ts')
const posts = read('app/api/communities/[id]/posts/route.ts')
const communityGuard = read('lib/server/community/community-integrity.ts')

// Communities: 20 independent source-level safety and feature-wiring controls.
test('C01 community creation requires authenticated session', /resolveAuthenticatedUser/.test(community))
test('C02 community creator identity is session-bound', /createdBy:\s*auth\.userId/.test(community))
test('C03 community creation uses durable fail-closed throttling', /communities:POST[\s\S]*failClosed:\s*true/.test(community))
test('C04 community membership uses durable fail-closed throttling', /failClosed:\s*true/.test(join))
test('C05 community leave uses a separate durable throttle bucket', /join:DELETE[\s\S]*failClosed:\s*true/.test(join))
test('C06 join and leave are authenticated', /resolveAuthenticatedUser/.test(join))
test('C07 join status maps pending and banned distinctly', /pendingApproval/.test(communityGuard) && /banned/.test(communityGuard))
test('C08 community role changes require authenticated actor', /resolveAuthenticatedUser/.test(roles))
test('C09 role changes use durable fail-closed throttling', /failClosed:\s*true/.test(roles))
test('C10 community IDs reject controls and excessive length', /length > 160/.test(communityGuard) && /\\u0000/.test(communityGuard))
test('C11 role target IDs are bounded and sanitized', /targetUserId\.length > 160/.test(roles))
test('C12 ownership transfer is not exposed by role API', /Ownership transfer is not available/.test(roles))
test('C13 moderation decisions require explicit boolean', /typeof body\.approve !== "boolean"/.test(requests))
test('C14 moderation decisions use durable fail-closed throttling', /failClosed:\s*true/.test(requests))
test('C15 moderation applicant IDs are bounded', /applicantId\.length > 160/.test(requests))
test('C16 platform moderation writes use durable throttling', /failClosed:\s*true/.test(platform))
test('C17 platform route sanitizes community IDs', /sanitizeCommunityId/.test(platform))
test('C18 community chat writes use durable throttling', /failClosed:\s*true/.test(chat))
test('C19 chat user IDs are bounded before RPC', /userId\.length > 160/.test(chat))
test('C20 community posts are viewer-scoped and uncached', /p_viewer_id:\s*auth\.userId/.test(posts) && /no-store/.test(posts))

const failed = checks.filter((x) => !x).length
console.log(`\nIndependent marketplace/community audit: ${checks.length - failed}/${checks.length} passed (${checks.length - 20} marketplace + 20 community controls)`)
process.exit(failed ? 1 : 0)
