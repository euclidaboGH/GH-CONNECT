#!/usr/bin/env node
import { readFile, readdir } from 'node:fs/promises'
import { join } from 'node:path'
const root=process.cwd(), checks=[]; const pass=(n,o,d='')=>checks.push({n,o,d})
const mig=await readFile(join(root,'supabase/migrations/20261022130001_marketplace_commerce_v2.sql'),'utf8')
const store=await readFile(join(root,'lib/server/marketplace/order-store.ts'),'utf8')
const route=await readFile(join(root,'app/api/marketplace/orders/[orderId]/commerce/route.ts'),'utf8')
const ui=await readFile(join(root,'components/ghc/marketplace-screen.tsx'),'utf8')
const canonical=await readFile(join(root,'supabase/GREENHAVEN-CANONICAL-SUPABASE-INSTALL.sql'),'utf8')
pass('migration',mig.includes('gh_marketplace_order_commerce_update'))
pass('escrow/delivery fields',mig.includes('escrow_status')&&mig.includes('delivery_status'))
pass('seller authorization',mig.includes('SELLER_ONLY')&&mig.includes('seller_fulfill'))
pass('buyer authorization',mig.includes('BUYER_ONLY')&&mig.includes('buyer_confirm'))
pass('dispute',mig.includes('DISPUTE_OPENED'))
pass('unpaid cancel protection',mig.includes('PAID_OR_STARTED'))
pass('server auth route',route.includes('resolveAuthenticatedUser')&&route.includes('AUTH_REQUIRED'))
pass('action allowlist',route.includes('ACTIONS=new Set'))
pass('durable store RPC',store.includes('updateCommerceOrder')&&store.includes('gh_marketplace_order_commerce_update'))
pass('metadata mapping',store.includes('escrowStatus')&&store.includes('deliveryStatus')&&store.includes('deliveredAt'))
pass('durable order UI',ui.includes('/api/marketplace/orders')&&ui.includes('Loading durable orders'))
pass('seller actions UI',ui.includes('Start fulfillment')&&ui.includes('Mark delivered'))
pass('buyer actions UI',ui.includes('Confirm received')&&ui.includes('Cancel'))
pass('dispute UI',ui.includes('Open dispute'))
pass('Pi order identity event',ui.includes('orderId: order.id'))
pass('canonical inclusion',canonical.includes('20261022130001_marketplace_commerce_v2.sql'))
const files=(await readdir(join(root,'supabase/migrations'))).filter(x=>/^\d{14}_.+\.sql$/.test(x)); pass('migration count',files.length===131,`count=${files.length}`)
for(const c of checks) console.log(`${c.o?'PASS':'FAIL'} ${c.n}${c.d?' — '+c.d:''}`)
if(checks.some(c=>!c.o)) process.exit(1); console.log(`PHASE30 ${checks.length}/${checks.length} PASS`)
