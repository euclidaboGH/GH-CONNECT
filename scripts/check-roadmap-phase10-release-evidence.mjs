import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const checks = [];
const ci = read('.github/workflows/ci.yml');
const pkg = JSON.parse(read('package.json'));
const envExample = read('.env.example');
const add = (name, ok) => checks.push({ name, ok: Boolean(ok) });
add('CI pins supported Node 24.15.0', /node-version:\s*24\.15\.0/.test(ci));
add('CI uses read-only repository permissions', /permissions:\s*\n\s*contents:\s*read/.test(ci));
add('CI runs locked npm install', /npm ci --legacy-peer-deps/.test(ci));
add('CI runs static contract suite', /npm run verify:static/.test(ci));
add('CI runs typecheck', /npm run typecheck/.test(ci));
add('CI runs lint', /npm run lint/.test(ci));
add('CI runs production build', /npm run build/.test(ci));
add('CI checks dependency lock integrity', /check-dependency-lock-integrity\.mjs/.test(ci));
add('CI runs secret/safety scanner', /npm run test:safety/.test(ci));
add('CI audits security headers', /npm run check:security-headers/.test(ci));
add('CI audits RLS coverage', /check-database-rls-coverage\.mjs/.test(ci));
add('CI audits SECURITY DEFINER ACLs', /check-security-definer-acl\.mjs/.test(ci));
add('CI checks migration release readiness', /check(?::|-)migration-release-readiness/.test(ci));
add('CI serializes per-ref work and cancels stale runs', /concurrency:[\s\S]*cancel-in-progress:\s*true/.test(ci));
add('Static suite includes Phase 9 closure', String(pkg.scripts?.['verify:static']).includes('check-roadmap-phase9-closure.mjs'));
add('Static suite includes Phase 10 evidence checker', String(pkg.scripts?.['verify:static']).includes('check-roadmap-phase10-release-evidence.mjs'));
add('Environment template documents placeholders only', /placeholders only/i.test(envExample));
add('Environment template warns against public secrets', /Private credentials must NOT use NEXT_PUBLIC_/i.test(envExample));
add('Environment template has Testnet E2E default disabled', /GHC_E2E_ALLOW_TESTNET=0/.test(envExample));
add('Environment template keeps payout execution disabled by default', /PI_EARNINGS_PAYOUT_EXECUTION_ENABLED=0/.test(envExample));
let failed = 0;
for (const c of checks) { console.log(`${c.ok ? 'PASS' : 'FAIL'} ${c.name}`); if (!c.ok) failed++; }
console.log(`Phase 10 release-evidence source checks: ${checks.length - failed}/${checks.length} passed`);
if (failed) process.exitCode = 1;
