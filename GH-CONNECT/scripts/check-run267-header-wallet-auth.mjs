#!/usr/bin/env node
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
const read = (p) => readFileSync(join(process.cwd(), p), 'utf8')
const css = read('app/globals.css')
const client = read('lib/client/pi-wallet-consent.ts')
const runtime = read('lib/pi-runtime.ts')
const serverAuth = read('lib/server/economy/auth.ts')
const consent = read('lib/server/identity/wallet-consent.ts')
const sheet = read('components/ghc/pi-withdraw-sheet.tsx')
const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
const checks = []
const add = (ok, label) => checks.push({ ok: Boolean(ok), label })
add(css.includes('Run #267 — premium compact section chrome'), 'Shared compact header polish is present as a final cascade layer')
add(css.includes('.gh-page-header-slim') && css.includes('.gh-marketplace-header') && css.includes('.gh-app-header-expanded'), 'Discovery, Marketplace and collapsing app headers share the compact chrome system')
add(css.includes('prefers-color-scheme: light') && css.includes('focus-visible'), 'Header surfaces support brighter light styling and keyboard focus')
add(css.includes('scrollbar-width: none') && css.includes('scroll-margin-top'), 'Header toolbars remain scrollable without visual scrollbar clutter')
add(client.includes('piAuthenticateOfficial(["wallet_address"])'), 'Wallet authorization requests only the wallet-address scope required for this consent')
add(!client.includes('piAuthenticateOfficial(["username", "payments", "wallet_address"])'), 'Wallet consent does not request unrelated Pi permissions')
add(runtime.includes('authResult?.user?.wallet_address || authResult?.user?.walletAddress'), 'Pi SDK wallet address extraction handles documented and camel-case SDK response variants')
add(serverAuth.includes('data.wallet_address || data.walletAddress || data.user?.wallet_address || data.user?.walletAddress'), 'Server Pi /v2/me parsing handles top-level and nested address variants')
add(consent.includes('review GreenHaven\'s app permissions in Pi Browser'), 'Missing wallet scope gives actionable permission-recovery instructions')
add(consent.includes('if (!piWalletAddress) return { ok: false, error: "PI_WALLET_ADDRESS_REQUIRED" }'), 'Wallet authorization still fails closed when neither trusted Pi source returns an address')
add(sheet.includes('min-h-12 w-full cursor-pointer') && sheet.includes('h-6 w-6'), 'Wallet consent remains a large accessible checkbox and tap target')
add(/^\d+\.\d+\.\d+$/.test(pkg.version) && lock.version === pkg.version && lock.packages?.['']?.version === pkg.version, 'Package and lockfile release identity remain synchronized')
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'} ${item.label}`)
const failed = checks.filter((item) => !item.ok)
console.log(`\nRun #267 header and wallet authorization: ${checks.length - failed.length}/${checks.length} passed`)
process.exit(failed.length ? 1 : 0)
