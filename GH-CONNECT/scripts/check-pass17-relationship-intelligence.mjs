import fs from "node:fs"
const checks = []
const read = (p) => fs.readFileSync(p, "utf8")
const pkg = JSON.parse(read("package.json"))
const release = read("lib/app-release.ts")
const messages = read("components/ghc/message-screen.tsx")
const outcomes = read("lib/relationship-outcomes.ts")
const migrations = fs.readdirSync("supabase/migrations").filter((f) => f.endsWith(".sql"))
const expect = (name, ok) => checks.push([name, Boolean(ok)])
expect("release 0.239.0", release.includes(`APP_RELEASE_VERSION = "${pkg.version}"`))
expect("relationship outcome model", outcomes.includes("buildRelationshipOutcome") && outcomes.includes("requestCount") && outcomes.includes("unreadCount"))
expect("message action centre", messages.includes("Relationship action centre") && messages.includes("relationshipOutcome"))
expect("requests remain separated", outcomes.includes("outside your accepted network stay separated"))
expect("real network state used", messages.includes("Array.isArray(matches)") && messages.includes("Array.isArray(friends)"))
expect("offline copy does not promise queue", messages.includes("Reconnect before sending new messages") && !messages.includes("messages queue on this device"))
expect("canonical routes preserved", messages.includes('navigateTo("discover")') && messages.includes('setFilter("communities")'))
expect("migration inventory retained", migrations.length >= 170)
for (const [name, ok] of checks) console.log(`${ok ? "PASS" : "FAIL"} — ${name}`)
const failed = checks.filter(([, ok]) => !ok)
console.log(`Pass 17 Relationship Intelligence: ${checks.length - failed.length}/${checks.length}`)
if (failed.length) process.exit(1)
